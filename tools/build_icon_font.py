"""Builds ui/assets/nickel-icons.ttf: the Lucide glyphs the overlay uses (ISC licence) plus brand logos from
Simple Icons (CC0) at private-use code points, and native/icon_codepoints.hpp with the code point table.

usage: python tools/build_icon_font.py <lucide-static package dir> <simple-icons package dir> tools/icon_table.py
"""
import json, os, sys, importlib.util
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.reverseContourPen import ReverseContourPen
from fontTools.svgLib.path import parse_path
import re

lucide, simple, table = sys.argv[1], sys.argv[2], sys.argv[3]
spec = importlib.util.spec_from_file_location("module_icons", table); mi = importlib.util.module_from_spec(spec); spec.loader.exec_module(mi)
codes = json.load(open(os.path.join(lucide, "font", "codepoints.json")))
BRANDS = {"discord": 0xF100, "github": 0xF101, "spotify": 0xF102}

def cp_of(name):
    return BRANDS[name[1:]] if name.startswith("@") else codes[name]

wanted = sorted({codes[v] for v in list(mi.M.values()) + list(mi.UI.values()) if not v.startswith("@")})
opts = subset.Options(); opts.layout_features = []; opts.name_IDs = ["*"]; opts.notdef_outline = True
font = TTFont(os.path.join(lucide, "font", "lucide.ttf"))
sub = subset.Subsetter(opts); sub.populate(unicodes=wanted); sub.subset(font)

# Brand logos: filled 24 x 24 SVG paths, y down -> font units (1000 per em, baseline 0, y up).
glyf, hmtx, cmap = font["glyf"], font["hmtx"], font["cmap"]
for name, cp in BRANDS.items():
    svg = open(os.path.join(simple, "icons", name + ".svg"), encoding="utf-8").read()
    d = " ".join(re.findall(r'\sd="([^"]+)"', svg))
    pen = TTGlyphPen(None)
    k = 1000 / 24
    parse_path(d, TransformPen(Cu2QuPen(ReverseContourPen(pen), 1.0, reverse_direction=False), (k, 0, 0, -k, 0, 1000)))
    gname = "brand_" + name
    glyf[gname] = pen.glyph(); hmtx[gname] = (1000, 0)   # glyf adds the name to the glyph order
    for table_ in cmap.tables:
        if table_.isUnicode(): table_.cmap[cp] = gname
out = os.path.join("ui", "assets", "nickel-icons.ttf"); font.save(out)

lines = ["// Generated by tools/build_icon_font.py: icon code points in ui/assets/nickel-icons.ttf.",
         "// Lucide icons (https://lucide.dev, ISC licence); brand logos from Simple Icons (https://simpleicons.org, CC0).",
         "#pragma once", "#include <cstdint>", "#include <cstring>", "", "namespace nicons {"]
for key, name in mi.UI.items():
    lines.append(f"inline constexpr uint16_t k_{key} = 0x{cp_of(name):04X};   // {name}")
for name, cp in BRANDS.items():
    lines.append(f"inline constexpr uint16_t k_brand_{name} = 0x{cp:04X};")
lines.append("struct ModuleIcon { const char* id; uint16_t code; };")
lines.append("inline constexpr ModuleIcon kModuleIcons[] = {")
for mid, name in mi.M.items():
    lines.append(f'  {{"{mid}", 0x{cp_of(name):04X}}},   // {name}')
lines.append("};")
lines.append("inline uint16_t ModuleIconOf(const char* id) { for (const auto& m : kModuleIcons) if (!std::strcmp(m.id, id)) return m.code; return 0; }")
lines.append("// Code point list for the ImGui atlas (pairs, zero terminated).")
allcp = sorted(set(wanted) | set(BRANDS.values()))
lines.append("inline const uint16_t kIconRanges[] = {" + ", ".join(f"0x{c:04X}, 0x{c:04X}" for c in allcp) + ", 0};")
lines.append("}")
open(os.path.join("native", "icon_codepoints.hpp"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("glyphs", len(allcp), "bytes", os.path.getsize(out))
