"""Write native/generated_signatures.hpp: the reference-build functions the overlay needs to find Nickel's game
addresses in a Minecraft build it has no profile for (native/game_resolve.hpp).

python tools/gen_signatures.py <reference Minecraft.Windows.exe (1.26.62.1)> [--out native/generated_signatures.hpp]

For every game address written in native/ (the same scan as tools/port_build.py):
- code inside a function of the exception table (.pdata): that function, whole;
- code outside any .pdata function (a leaf function or padding): its bytes up to the first ret, plus the .pdata
  functions on both sides, whose position gives the leaf's;
- data (.rdata / .data): up to four RIP-relative instructions of the reference build that point at it, with the
  function holding each one (added to the list).
The overlay compares each function with the running game's functions of the same size, relative fields (RIP-relative
displacements, rel32 branch targets) masked, then reads each data address from the matching instruction.
"""
import bisect
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_game_builds  # noqa: E402
import port_build  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MAX_EXTRA = 0x1000   # largest function added only to read a data address
LEAF_MAX = 0x200


def leaf_bytes(ref, start):
    size = 0
    for ins in port_build.MD.disasm(ref['rd'](start, LEAF_MAX), start):
        size += ins.size
        if ins.mnemonic in ('ret', 'int3') or size >= LEAF_MAX - 16: break
    return size


def used_addresses(ref):
    """Game addresses written in native/ ({address: (section, file)}), with the scan of tools/check_game_builds.py:
    a line marked "// not a game address: <reason>" holds constants only (colours, masks, sizes)."""
    sections = {n: (ref['secs'][n][0], ref['secs'][n][0] + ref['secs'][n][1]) for n in ('.text', '.rdata', '.data')}
    found = {}
    for f in sorted((ROOT / 'native').glob('*.[hc]pp')):
        if f.name.startswith('generated_build_') or f.name in ('generated_signatures.hpp', 'game_build.hpp'): continue
        for line in f.read_text(encoding='utf-8', errors='replace').splitlines():
            addresses, _ = check_game_builds.scan_line(line, sections)
            for v, sec in addresses.items(): found.setdefault(v, (sec, f.name))
    return found


def main():
    ref = port_build.load(sys.argv[1])
    out = Path(sys.argv[sys.argv.index('--out') + 1]) if '--out' in sys.argv else ROOT / 'native' / 'generated_signatures.hpp'
    funcs = ref['funcs']; starts = [f[0] for f in funcs]
    used = used_addresses(ref)
    chosen = {}   # start -> (size, leaf)

    def containing(v):
        i = bisect.bisect_right(starts, v) - 1
        return i if i >= 0 and funcs[i][0] <= v < funcs[i][1] else None

    leaves = 0
    for v, (sec, _) in sorted(used.items()):
        if sec != '.text': continue
        i = containing(v)
        if i is not None:
            chosen[funcs[i][0]] = (funcs[i][1] - funcs[i][0], 0)
            continue
        i = bisect.bisect_right(starts, v) - 1
        for k in (i, i + 1):
            if 0 <= k < len(funcs): chosen.setdefault(funcs[k][0], (funcs[k][1] - funcs[k][0], 0))
        chosen[v] = (leaf_bytes(ref, v), 1); leaves += 1
    data = sorted(v for v, (sec, _) in used.items() if sec != '.text')
    xrefs = port_build.data_xrefs(ref, set(data))
    data_refs = []
    for t in data:
        picks = []
        for st in sorted(xrefs.get(t, []), key=lambda st: (containing(st) is None or funcs[containing(st)][0] not in chosen, st)):
            i = containing(st)
            if i is None: continue
            fb, fe = funcs[i]
            if fb not in chosen and fe - fb > MAX_EXTRA: continue
            chosen.setdefault(fb, (fe - fb, 0)); picks.append((fb, st - fb))
            if len(picks) == 4: break
        for fb, off in picks: data_refs.append((t, fb, off))
    order = sorted(chosen)
    index = {s: k for k, s in enumerate(order)}
    CONTEXT = 8   # sizes of the .pdata functions before and after each function: which copy of a common function it is

    def context(s):
        if chosen[s][1]: return [0] * (2 * CONTEXT)
        i = starts.index(s) if s in starts else bisect.bisect_left(starts, s)
        around = [funcs[j] for j in list(range(i - CONTEXT, i)) + list(range(i + 1, i + 1 + CONTEXT))]
        return [e - b for b, e in around]
    blob = bytearray(); table = []
    for s in order:
        size, leaf = chosen[s]
        table.append((s, size, len(blob), leaf)); blob += ref['rd'](s, size)
    text_va, text_size = ref['secs']['.text'][0], ref['secs']['.text'][1]
    lines = ['// Generated by tools/gen_signatures.py from the reference build (Minecraft 1.26.62.1). Do not edit.',
             '// The reference functions holding every game address Nickel uses (native/game_resolve.hpp finds them in a',
             '// build without a profile): reference address, size, offset of its bytes in kSignatureBytes, leaf flag (no',
             '// .pdata entry: bytes up to the first ret); then the RIP-relative instructions that give each data address.',
             '#pragma once', '#include <cstdint>', 'namespace game {',
             'struct SignatureFunction{uint32_t ref,size,bytes;uint32_t leaf;};',
             'struct SignatureData{uint32_t ref;uint32_t function;uint32_t offset;};   // function: index in kSignatureFunctions',
             f'inline constexpr unsigned kSignatureContext={CONTEXT};   // .pdata neighbours on each side in kSignatureNeighbours',
             f'inline constexpr uint32_t kSignatureText[2]={{0x{text_va:x}u,0x{text_size:x}u}};   // reference .text address and size',
             'inline constexpr SignatureFunction kSignatureFunctions[]={']
    lines += [f'{{0x{s:x}u,{size}u,{at}u,{leaf}u}},' for s, size, at, leaf in table]
    lines += ['};', '// Sizes of the 8 .pdata functions before and the 8 after each function (zeros for a leaf).',
              'inline constexpr uint32_t kSignatureNeighbours[][2*kSignatureContext]={']
    lines += ['{' + ','.join(str(v) for v in context(s)) + '},' for s in order]
    lines += ['};', 'inline constexpr SignatureData kSignatureData[]={']
    lines += [f'{{0x{t:x}u,{index[fb]}u,{off}u}},' for t, fb, off in data_refs]
    lines += ['};', 'inline constexpr uint8_t kSignatureBytes[]={']
    for k in range(0, len(blob), 40):
        lines.append(','.join(str(b) for b in blob[k:k + 40]) + ',')
    lines += ['};', '}', '']
    out.write_text('\n'.join(lines), encoding='utf-8')
    missing = [hex(t) for t in data if not any(r[0] == t for r in data_refs)]
    print(f'{out.name}: {len(table)} functions ({leaves} leaves), {len(data_refs)} data references, {len(blob)} bytes;'
          f' data without a reference (constants): {missing}')


if __name__ == '__main__':
    main()
